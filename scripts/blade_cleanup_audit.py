#!/usr/bin/env python3

from __future__ import annotations

from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
VIEWS_DIR = ROOT / "resources" / "views"
OUTPUT = ROOT / "artifacts" / "blade_cleanup_inventory.md"


def collect_rows() -> list[dict[str, int | str]]:
    rows: list[dict[str, int | str]] = []

    for path in sorted(VIEWS_DIR.rglob("*.blade.php")):
        text = path.read_text(encoding="utf-8", errors="ignore")
        rows.append(
            {
                "path": str(path.relative_to(ROOT)),
                "lines": text.count("\n") + 1,
                "scripts": text.count("<script"),
                "styles": text.count("<style"),
                "dom_ready": text.count("document.addEventListener('DOMContentLoaded'"),
                "intervals": text.count("setInterval("),
                "reloads": text.count("window.location.reload("),
                "bootstrap_513": int("bootstrap@5.1.3" in text),
                "bootstrap_530": int("bootstrap@5.3.0" in text),
                "alpine_282": int("alpinejs@2.8.2" in text),
                "alpine_3x": int("alpinejs@3." in text),
                "jquery_360": int("jquery-3.6.0" in text),
            }
        )

    return rows


def write_report(rows: list[dict[str, int | str]]) -> None:
    totals = Counter()
    for row in rows:
        for key in (
            "scripts",
            "styles",
            "dom_ready",
            "intervals",
            "reloads",
            "bootstrap_513",
            "bootstrap_530",
            "alpine_282",
            "alpine_3x",
            "jquery_360",
        ):
            totals[key] += int(row[key])

    top_rows = sorted(
        rows,
        key=lambda row: (
            int(row["lines"]),
            int(row["scripts"]),
            int(row["styles"]),
        ),
        reverse=True,
    )[:20]

    lines = [
        "# Blade Cleanup Inventory",
        "",
        "Generated by `scripts/blade_cleanup_audit.py`.",
        "",
        "## Summary",
        "",
        f"- Blade files scanned: {len(rows)}",
        f"- `<script>` tags: {totals['scripts']}",
        f"- `<style>` tags: {totals['styles']}",
        f"- `DOMContentLoaded` hooks: {totals['dom_ready']}",
        f"- `setInterval(...)` calls: {totals['intervals']}",
        f"- `window.location.reload(...)` calls: {totals['reloads']}",
        "",
        "## Runtime Drift",
        "",
        f"- Bootstrap 5.1.3 pages: {totals['bootstrap_513']}",
        f"- Bootstrap 5.3.0 pages: {totals['bootstrap_530']}",
        f"- Alpine 2.8.2 pages: {totals['alpine_282']}",
        f"- Alpine 3.x pages: {totals['alpine_3x']}",
        f"- jQuery 3.6.0 pages: {totals['jquery_360']}",
        "",
        "## Largest Blade Surfaces",
        "",
        "| File | Lines | Scripts | Styles | DOM Ready | Intervals | Reloads |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]

    for row in top_rows:
        lines.append(
            "| {path} | {lines} | {scripts} | {styles} | {dom_ready} | {intervals} | {reloads} |".format(
                **row
            )
        )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    rows = collect_rows()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    write_report(rows)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
